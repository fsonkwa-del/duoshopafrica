export function formatMoney(
  amountMinor: bigint,
  currency: string,
  locale: Locale,
): string {
  const formatter = new Intl.NumberFormat(locale === "fr" ? "fr-CM" : "en-CM", {
    style: "currency",
    currency,
  });
  const digits = formatter.resolvedOptions().maximumFractionDigits ?? 0;
  const factor = 10n ** BigInt(digits);
  if (
    amountMinor > BigInt(Number.MAX_SAFE_INTEGER) ||
    amountMinor < BigInt(Number.MIN_SAFE_INTEGER)
  )
    throw new RangeError("Display amount out of safe range");
  return formatter.format(Number(amountMinor) / Number(factor));
}

// Horodatages affichés dans le fuseau métier explicite (Douala), stockés en UTC.
export function formatDateTime(iso: string, locale: Locale): string {
  return new Intl.DateTimeFormat(locale === "fr" ? "fr-CM" : "en-CM", {
    dateStyle: "medium",
    timeStyle: "short",
    timeZone: "Africa/Douala",
  }).format(new Date(iso));
}
